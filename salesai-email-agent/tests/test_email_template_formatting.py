    # 6. Angry customer
    def test_06_angry_customer(self):
        context = ["Orders delayed due to weather or transit disruptions will be expedited. Contact support with Order ID."]
        fallback = _fallback_reply(
            strategy="empathy_first",
            intent="complaint",
            emotion="angry",
            context_docs=context,
        )
        cleaned = normalize_customer_response(fallback, customer_name="Frank")
        
        self.assertTrue(cleaned.startswith("Hi Frank,"))
        self.assertTrue(cleaned.endswith(STANDARD_CLOSING))
        self.assertIn("frustration", cleaned.lower())

    # 7. Follow-up email using "it" / "that" / "same issue"
    def test_07_follow_up_with_pronouns(self):
        memory = CustomerMemory(
            profile=CustomerProfile(customer_id="cust-7", email="grace@example.com", name="Grace Hopper"),
            open_issues=[
                CustomerIssue(id="iss-1", customer_id="cust-7", issue_title="Charged twice for Order SFX-990", status="open")
            ],
            is_empty=False,
        )
        context = ["Duplicate charges on UPI/Cards are auto-reversed within 24-48 hours. Bank processing may take 3-5 business days."]
        fallback = _fallback_reply(
            strategy="status_update",
            intent="refund_status",
            emotion="frustrated",
            context_docs=context,
            customer_memory=memory,
        )
        cleaned = normalize_customer_response(fallback, customer_name="Grace Hopper")
        
        self.assertTrue(cleaned.startswith("Hi Grace,"))
        self.assertTrue(cleaned.endswith(STANDARD_CLOSING))
        self.assertIn("charged twice", cleaned.lower())

