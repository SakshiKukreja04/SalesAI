"""Comprehensive unit test suite for ShopiFyX Plain-Text Customer Email Standardization.

Covers all 16 required test scenarios:
1. Simple product question
2. Order-status question
3. Refund request
4. Return request
5. Warranty question
6. Angry customer
7. Follow-up email using 'it', 'that', or 'same issue'
8. Customer with previous conversation history
9. Transactional action successfully initiated
10. Transactional action rejected / policy boundary
11. Escalation response / missing context fallback
12. Missing customer name (Greeting strictly 'Hi,')
13. Response containing Markdown generated by LLM (cleaned to plain text)
14. Response containing excessive blank lines (normalized to \\n\\n)
15. Response containing 'Here is your response:' preamble (stripped)
16. Duplicate greeting / sign-off handling (deduplicated)
"""

from __future__ import annotations

import unittest

from app.agents.decision import validate_email_response
from app.agents.generator import (
    STANDARD_CLOSING,
    _fallback_reply,
    normalize_customer_response,
    sanitize_customer_reply,
)
from app.memory.memory_models import (
    CustomerIssue,
    CustomerMemory,
    CustomerProfile,
)
from app.rag.response_validator import (
    SAFE_FALLBACK_RESPONSE,
    has_formatting_issues,
    validate_response,
)


class TestEmailTemplateFormatting(unittest.TestCase):
    """Test suite for ShopiFyX Plain-Text Email Standardization & Validation Pipeline."""

    # 1. Simple product question
    def test_01_simple_product_question(self):
        context = ["AeroRun Running Shoes feature breathable engineered mesh and an EVA foam cushioned midsole. Priced at $120."]
        raw_llm = (
            "Hi Alice,\n\n"
            "Thank you for reaching out about our AeroRun Running Shoes.\n\n"
            "The shoes feature breathable engineered mesh and an EVA foam cushioned midsole for optimal comfort.\n\n"
            "Best regards,\nCustomer Support Team\nShopiFyX"
        )
        cleaned = normalize_customer_response(raw_llm, customer_name="Alice")
        val = validate_email_response(cleaned, context, intent="product_inquiry", emotion="neutral")
        
        self.assertTrue(val["valid"])
        self.assertTrue(cleaned.startswith("Hi Alice,"))
        self.assertTrue(cleaned.endswith(STANDARD_CLOSING))
        self.assertIn("breathable engineered mesh", cleaned.lower())
        self.assertNotIn("**", cleaned)
        self.assertNotIn("##", cleaned)
        self.assertNotIn("•", cleaned)

