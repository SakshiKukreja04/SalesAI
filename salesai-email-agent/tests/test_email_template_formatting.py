    # 11. Escalation response / missing KB
    def test_11_escalation_response_missing_context(self):
        fallback = normalize_customer_response(SAFE_FALLBACK_RESPONSE, customer_name="Karen")
        
        self.assertTrue(fallback.startswith("Hi Karen,"))
        self.assertTrue(fallback.endswith(STANDARD_CLOSING))
        self.assertIn("reviewing your request", fallback)
        self.assertNotIn("memory", fallback.lower())
        self.assertNotIn("rag", fallback.lower())

    # 12. Missing customer name (Greeting strictly 'Hi,')
    def test_12_missing_customer_name(self):
        raw = "We have received your message and will check the delivery status."
        
        for empty_name in ["", "   ", "Valued Customer", "Customer", "none", "None", "null"]:
            cleaned = normalize_customer_response(raw, customer_name=empty_name)
            self.assertTrue(cleaned.startswith("Hi,\n\n"), f"Failed for name '{empty_name}': starts with {cleaned[:20]}")
            self.assertNotIn("Valued Customer", cleaned)
            self.assertNotIn("Dear", cleaned)
            self.assertTrue(cleaned.endswith(STANDARD_CLOSING))

    # 13. Response containing Markdown generated by LLM
    def test_13_response_containing_markdown(self):
        raw = (
            "Hi Leo,\n\n"
            "### Delivery Updates\n\n"
            "Your **Order SFX-771** has shipped via **Express Courier**.\n\n"
            "**Next Steps:**\n"
            "* Wait 2-3 business days for delivery.\n"
            "* Track your package online at tracking link.\n\n"
            "Best regards,\nCustomer Support Team"
        )
        cleaned = normalize_customer_response(raw, customer_name="Leo")
        
        self.assertNotIn("**", cleaned)
        self.assertNotIn("###", cleaned)
        self.assertNotIn("* ", cleaned)
        self.assertFalse(has_formatting_issues(cleaned)[0])
        self.assertTrue(cleaned.startswith("Hi Leo,"))
        self.assertTrue(cleaned.endswith(STANDARD_CLOSING))

    # 14. Response containing excessive blank lines
    def test_14_response_excessive_blank_lines(self):
        raw = (
            "Hi Mia,\n\n\n\n\n"
            "Thank you for contacting us.\n\n\n\n\n"
            "Your return has been processed.\n\n\n\n\n"
            "Best regards,\nCustomer Support Team"
        )
        cleaned = normalize_customer_response(raw, customer_name="Mia")
        
        self.assertNotIn("\n\n\n", cleaned)
        self.assertTrue(cleaned.startswith("Hi Mia,\n\nThank you for contacting us.\n\nYour return has been processed."))
        self.assertTrue(cleaned.endswith(STANDARD_CLOSING))

    # 15. Response containing "Here is your response:" preamble
    def test_15_response_containing_preamble(self):
        raw = (
            "Here is your response:\n\n"
            "Hi Noah,\n\n"
            "Thank you for contacting ShopiFyX support.\n\n"
            "We have updated your shipping address for Order SFX-901.\n\n"
            "Best regards,\nCustomer Support Team\nShopiFyX"
        )
        cleaned = normalize_customer_response(raw, customer_name="Noah")
        
        self.assertNotIn("Here is your response", cleaned)
        self.assertTrue(cleaned.startswith("Hi Noah,"))
        self.assertTrue(cleaned.endswith(STANDARD_CLOSING))

    # 16. Duplicate greeting and sign-off
    def test_16_duplicate_greeting_and_signoff(self):
        raw = (
            "Hi Olivia,\n\n"
            "Hi Olivia,\n\n"
            "Thank you for reaching out.\n\n"
            "Your order will arrive on Monday.\n\n"
            "Best regards,\n"
            "Customer Support Team\n"
            "ShopiFyX\n\n"
            "Best regards,\n"
            "ShopiFyX Support Team"
        )
        cleaned = normalize_customer_response(raw, customer_name="Olivia")
        
        self.assertEqual(cleaned.count("Hi Olivia,"), 1)
        self.assertEqual(cleaned.count("Best regards,"), 1)
        self.assertEqual(cleaned.count("Customer Support Team"), 1)
        self.assertTrue(cleaned.startswith("Hi Olivia,"))
        self.assertTrue(cleaned.endswith(STANDARD_CLOSING))


